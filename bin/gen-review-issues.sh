#!/usr/bin/env bash
#
# gen-review-issues.sh — generate one GitHub "Tier B review" issue per chapter
# from the in-file markers, so a human can check off each diagram and each
# garbled/unverified table against the source scan.
#
# It scrapes two marker kinds out of the chapters dir (CHDIR):
#   <!-- FIGURE x.y: ... -->       -> "Diagrams" checklist item
#   <!-- TODO(tier-b): ... -->     -> "Tables / values to verify" checklist item
# Each item keeps its source-line number so a reviewer can jump to it.
#
# Chapters with no markers are skipped. The script is dry-run by default: it
# writes issue bodies to an output dir and prints a summary. Pass --create to
# actually open the issues with `gh` (label: tier-b).
#
# Usage:
#   bin/gen-review-issues.sh                 # dry run -> build/review-issues/
#   bin/gen-review-issues.sh --create        # also: gh issue create per chapter
#   CHDIR=docs/<book>/chapters OUT=/tmp/x bin/gen-review-issues.sh   # per book
#
set -euo pipefail

CHDIR="${CHDIR:-docs/pc-8201a-tech-ref/chapters}"
OUT="${OUT:-build/review-issues}"
LABEL="tier-b"
create=0
[ "${1:-}" = "--create" ] && create=1

if [ ! -d "$CHDIR" ]; then
  echo "ERROR: $CHDIR not found — run from the repo root." >&2
  exit 1
fi
if [ "$create" -eq 1 ] && ! command -v gh >/dev/null 2>&1; then
  echo "ERROR: --create needs the gh CLI (and an authenticated session)." >&2
  exit 1
fi

mkdir -p "$OUT"
echo "Mode   : $([ "$create" -eq 1 ] && echo 'CREATE (gh issue create)' || echo 'dry run (write bodies only)')"
echo "Output : $OUT/"
echo "Label  : $LABEL"
echo

# strip "<!-- " / " -->" wrappers and the "TODO(tier-b): " tag from a comment line
strip() { sed -E 's/^[[:space:]]*<!-- ?//; s/ ?-->[[:space:]]*$//; s/^TODO\(tier-b\): ?//'; }

total_fig=0 total_tbl=0 made=0

for f in "$CHDIR"/*.md; do
  base="$(basename "$f")"
  num="${base%%-*}"                       # NN
  raw_title="$(head -1 "$f" | sed -E 's/^#[[:space:]]*//')"
  case "$raw_title" in
    Chapter*) title="$raw_title" ;;       # already "Chapter N: ..."
    *)        title="Chapter ${num#0}: $raw_title" ;;  # synthesize (e.g. ch7)
  esac

  figs="$(grep -nE '<!-- FIGURE' "$f" || true)"
  tbls="$(grep -nE '<!-- TODO\(tier-b\)' "$f" || true)"
  [ -z "$figs" ] && [ -z "$tbls" ] && continue

  nf=$([ -z "$figs" ] && echo 0 || printf '%s\n' "$figs" | wc -l | tr -d ' ')
  nt=$([ -z "$tbls" ] && echo 0 || printf '%s\n' "$tbls" | wc -l | tr -d ' ')
  total_fig=$((total_fig+nf)); total_tbl=$((total_tbl+nt)); made=$((made+1))

  body="$OUT/${num}.md"
  {
    echo "Tier B review checklist for **${title}** (\`${f}\`)."
    echo
    echo "Auto-generated by \`bin/gen-review-issues.sh\` from in-file markers."
    echo "Re-run the script to refresh. Each item links to its source line."
    echo "Verify every value against the original scan — OCR'd numbers are not authoritative."
    echo
    if [ -n "$figs" ]; then
      echo "## Diagrams (figure → mermaid / table / image)"
      while IFS=: read -r ln text; do
        echo "- [ ] $(printf '%s' "$text" | strip) <sub>(L${ln})</sub>"
      done <<<"$figs"
      echo
    fi
    if [ -n "$tbls" ]; then
      echo "## Tables / values to verify"
      while IFS=: read -r ln text; do
        echo "- [ ] $(printf '%s' "$text" | strip) <sub>(L${ln})</sub>"
      done <<<"$tbls"
      echo
    fi
    echo "---"
    echo "_Pipeline + per-figure-type policy: see \`docs/ocr-workflow.md\`._"
  } > "$body"

  printf "  %-44s figures=%-3s tables=%-3s -> %s\n" "$title" "$nf" "$nt" "$body"

  if [ "$create" -eq 1 ]; then
    url="$(gh issue create --title "Tier B review: ${title}" \
            --body-file "$body" --label "$LABEL" 2>&1)" \
      && echo "      created: $url" \
      || { echo "      gh issue create FAILED: $url" >&2; }
  fi
done

echo
echo "Chapters with work: $made   figures: $total_fig   tables: $total_tbl"
[ "$create" -eq 0 ] && echo "Dry run only. Review bodies in $OUT/, then re-run with --create."
echo "Done."
